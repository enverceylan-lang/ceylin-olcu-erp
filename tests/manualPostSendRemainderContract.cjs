const fs = require('fs');
const assert = require('assert');
const path = require('path');
const service = fs.readFileSync(path.join(__dirname,'../src/lib/syncService.ts'),'utf8');
const queue = fs.readFileSync(path.join(__dirname,'../src/lib/localSyncQueueDb.ts'),'utf8');
const block = service.match(/async function runMeasurementManualSync\([\s\S]+?\n}\n\nlet measurementManualInFlight/);
assert(block, 'manual coordinator missing');
assert(/direction === 'push'[\s\S]*?pushMeasurementSyncEvents\(\)[\s\S]*?getPendingSyncEvents\(activeScope,\s*1,\s*["']MEASUREMENT["']\)/.test(block[0]), 'post-push remaining query must filter MEASUREMENT');
assert(/entityTypeFilter\?: 'MEASUREMENT'/.test(queue), 'filter parameter must be declared');
const idxFilter = queue.indexOf("if (entityTypeFilter && event.entityType !== entityTypeFilter) return false;");
const idxMutation = queue.indexOf('bulkUpdate(', queue.indexOf('const scopePartitionedEvents'));
assert(idxFilter >= 0 && idxMutation > idxFilter, 'filter must precede queue mutations');
const records = [{entityType:'CUSTOMER', syncStatus:'PENDING'}, {entityType:'MEASUREMENT', syncStatus:'SYNCED'}];
const pending = (events, filter) => events.filter(e=>['PENDING','ERROR'].includes(e.syncStatus) && e.entityType===filter);
assert.strictEqual(pending(records,'MEASUREMENT').length,0,'pending customer must not fail successful manual measurement push');
assert.strictEqual(records[0].syncStatus,'PENDING','customer must remain untouched');
records[1].syncStatus='PENDING';
assert.strictEqual(pending(records,'MEASUREMENT').length,1,'pending measurement must fail');
